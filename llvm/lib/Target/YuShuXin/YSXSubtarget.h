#define GET_YSX_MACRO_FUSION_PRED_DECL
#include "YSXGenMacroFusion.inc"

#define GET_SUBTARGETINFO_HEADER
#include "YSXGenSubtargetInfo.inc"

namespace llvm {
class StringRef;

namespace YSXTuneInfoTable {

struct YSXTuneInfo {
  const char *Name;
  uint8_t PrefFunctionAlignment;
  uint8_t PrefLoopAlignment;

  // Information needed by LoopDataPrefetch.
  uint16_t CacheLineSize;
  uint16_t PrefetchDistance;
  uint16_t MinPrefetchStride;
  unsigned MaxPrefetchIterationsAhead;

  unsigned MinimumJumpTableEntries;

  // Tail duplication threshold at -O3.
  unsigned TailDupAggressiveThreshold;

  unsigned MaxStoresPerMemsetOptSize;
  unsigned MaxStoresPerMemset;

  unsigned MaxGluedStoresPerMemcpy;
  unsigned MaxStoresPerMemcpyOptSize;
  unsigned MaxStoresPerMemcpy;

  unsigned MaxStoresPerMemmoveOptSize;
  unsigned MaxStoresPerMemmove;

  unsigned MaxLoadsPerMemcmpOptSize;
  unsigned MaxLoadsPerMemcmp;

  // The direction of PostRA scheduling.
  MISched::Direction PostRASchedDirection;
};

#define GET_YSXTuneInfoTable_DECL
#include "YSXGenSearchableTables.inc"
} // namespace YSXTuneInfoTable

class YSXSubtarget : public YSXGenSubtargetInfo {
public:
private:
  virtual void anchor();

  bool IsLittleEndian = true;

#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER) \
  bool ATTRIBUTE = DEFAULT;
#include "YSXGenSubtargetInfo.inc"

  YSXABI::ABI TargetABI = YSXABI::ABI_Unknown;
  std::bitset<YSX::NUM_TARGET_REGS> UserReservedRegister;
  const YSXTuneInfoTable::YSXTuneInfo *TuneInfo;

  YSXFrameLowering FrameLowering;
  YSXInstrInfo InstrInfo;
  YSXTargetLowering TLInfo;

  /// Initializes using the passed in CPU and feature strings so that we can
  /// use initializer lists for subtarget initialization.
  YSXSubtarget &initializeSubtargetDependencies(const Triple &TT,
                                                  StringRef CPU,
                                                  StringRef TuneCPU,
                                                  StringRef FS,
                                                  StringRef ABIName);

public:
  // Initializes the data members to match that of the specified triple.
  YSXSubtarget(const Triple &TT, StringRef CPU, StringRef TuneCPU,
                 StringRef FS, StringRef ABIName, const TargetMachine &TM);

  ~YSXSubtarget() override;

  // Parses features string setting specified subtarget options. The
  // definition of this function is auto-generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  const YSXFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const YSXInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const YSXRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const YSXTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  bool enableMachineScheduler() const override { return true; }

  bool enablePostRAScheduler() const override { return UsePostRAScheduler; }

  Align getPrefFunctionAlignment() const {
    return Align(TuneInfo->PrefFunctionAlignment);
  }
  Align getPrefLoopAlignment() const {
    return Align(TuneInfo->PrefLoopAlignment);
  }

#define GET_SUBTARGETINFO_MACRO(ATTRIBUTE, DEFAULT, GETTER) \
  bool GETTER() const { return ATTRIBUTE; }
#include "YSXGenSubtargetInfo.inc"

  bool is64Bit() const { return IsRV64; }
  bool isLittleEndian() const { return IsLittleEndian; }
  MVT getXLenVT() const {
    return MVT::i64;
  }
  unsigned getXLen() const {
    return 64;
  }
  unsigned getFLen() const {
    return 0;
  }

  YSXABI::ABI getTargetABI() const { return TargetABI; }
  bool isSoftFPABI() const { return true; }
  bool isRegisterReservedByUser(Register i) const override {
    assert(i.id() < YSX::NUM_TARGET_REGS && "Register out of range");
    return UserReservedRegister[i.id()];
  }

  // XRay support - require D and C extensions.
  bool isXRaySupported() const override { return false; }

  unsigned getMaxInterleaveFactor() const {
    return 1;
  }

  bool hasOptimizedSegmentLoadStore(unsigned NF) const {
    return false;
  }

  unsigned getDLenFactor() const { return 1; }

protected:
  // SelectionDAGISel related APIs.
  std::unique_ptr<const SelectionDAGTargetInfo> TSInfo;

public:
  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override;

  bool isTargetAndroid() const { return getTargetTriple().isAndroid(); }
  bool isTargetFuchsia() const { return getTargetTriple().isOSFuchsia(); }

  bool useConstantPoolForLargeInts() const;

  // Maximum cost used for building integers, integers will be put into constant
  // pool if exceeded.
  unsigned getMaxBuildIntsCost() const;

  bool enableSubRegLiveness() const override;

  bool enableMachinePipeliner() const override;

  bool useDFAforSMS() const override { return false; }

  bool useAA() const override;

  unsigned getCacheLineSize() const override {
    return TuneInfo->CacheLineSize;
  };
  unsigned getPrefetchDistance() const override {
    return TuneInfo->PrefetchDistance;
  };
  unsigned getMinPrefetchStride(unsigned NumMemAccesses,
                                unsigned NumStridedMemAccesses,
                                unsigned NumPrefetches,
                                bool HasCall) const override {
    return TuneInfo->MinPrefetchStride;
  };
  unsigned getMaxPrefetchIterationsAhead() const override {
    return TuneInfo->MaxPrefetchIterationsAhead;
  };
  bool enableWritePrefetching() const override { return true; }

  unsigned getMinimumJumpTableEntries() const;

  unsigned getTailDupAggressiveThreshold() const {
    return TuneInfo->TailDupAggressiveThreshold;
  }

  unsigned getMaxStoresPerMemset(bool OptSize) const {
    return OptSize ? TuneInfo->MaxStoresPerMemsetOptSize
                   : TuneInfo->MaxStoresPerMemset;
  }

  unsigned getMaxGluedStoresPerMemcpy() const {
    return TuneInfo->MaxGluedStoresPerMemcpy;
  }

  unsigned getMaxStoresPerMemcpy(bool OptSize) const {
    return OptSize ? TuneInfo->MaxStoresPerMemcpyOptSize
                   : TuneInfo->MaxStoresPerMemcpy;
  }

  unsigned getMaxStoresPerMemmove(bool OptSize) const {
    return OptSize ? TuneInfo->MaxStoresPerMemmoveOptSize
                   : TuneInfo->MaxStoresPerMemmove;
  }

  unsigned getMaxLoadsPerMemcmp(bool OptSize) const {
    return OptSize ? TuneInfo->MaxLoadsPerMemcmpOptSize
                   : TuneInfo->MaxLoadsPerMemcmp;
  }

  MISched::Direction getPostRASchedDirection() const {
    return TuneInfo->PostRASchedDirection;
  }

  void overrideSchedPolicy(MachineSchedPolicy &Policy,
                           const SchedRegion &Region) const override;

  void overridePostRASchedPolicy(MachineSchedPolicy &Policy,
                                 const SchedRegion &Region) const override;
};
} // namespace llvm

#endif
