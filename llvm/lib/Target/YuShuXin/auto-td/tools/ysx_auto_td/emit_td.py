from dataclasses import dataclass
from pathlib import Path
import re

from .opcodes import source_key_from_mnemonic


GENERATED_HEADER = "// generated by ysx_auto_td_gen\n"
OUTPUTS = (
    "YSXGenAutoTinyFInstrInfo.inc",
    "YSXGenAutoTinyVInstrInfo.inc",
    "YSXGenAutoTinyVPseudos.inc",
    "YSXGenAutoTinyVPatterns.inc",
    "YSXGenAutoTinyVBuiltins.inc",
)


@dataclass(frozen=True)
class Assignment:
    msb: int
    lsb: int
    expr: str


def write_td_outputs(out_dir: Path, instructions) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    tiny_f = [
        instruction
        for instruction in instructions
        if instruction.path.parent.name == "tiny-f"
    ]
    tiny_v = [
        instruction
        for instruction in instructions
        if instruction.path.parent.name == "tiny-v"
    ]

    content = {
        "YSXGenAutoTinyFInstrInfo.inc": _emit_tiny_f_instrinfo(tiny_f),
        "YSXGenAutoTinyVInstrInfo.inc": _emit_tiny_v_instrinfo(tiny_v),
        "YSXGenAutoTinyVPseudos.inc": _emit_tiny_v_pseudos(tiny_v),
        "YSXGenAutoTinyVPatterns.inc": _emit_tiny_v_patterns(tiny_v),
        "YSXGenAutoTinyVBuiltins.inc": _emit_tiny_v_builtins(tiny_v),
    }

    for output in OUTPUTS:
        (out_dir / output).write_text(content[output])


def _empty_file(name: str) -> str:
    return f"{GENERATED_HEADER}// {name}: no generated records yet\n"


def _emit_tiny_f_instrinfo(instructions) -> str:
    if not instructions:
        return _empty_file("tiny-f instrinfo")
    return _emit_instrinfo(instructions).rstrip() + "\n"


def _emit_tiny_v_instrinfo(instructions) -> str:
    lines = [
        GENERATED_HEADER.rstrip(),
        "",
        "// YSX tiny-v operand support generated from structured YAML.",
        "def YSXAutoVMaskAsmOperand : AsmOperandClass {",
        '  let Name = "YSXAutoVMaskRegOpOperand";',
        '  let RenderMethod = "addRegOperands";',
        '  let PredicateMethod = "isV0Reg";',
        '  let ParserMethod = "parseVMaskReg";',
        "  let IsOptional = 1;",
        '  let DefaultMethod = "defaultMaskRegOp";',
        '  let DiagnosticType = "InvalidYSXAutoVMaskRegister";',
        '  let DiagnosticString = "operand must be v0.t";',
        "}",
        "",
        "def YSXAutoVMaskOp : RegisterOperand<VMV0> {",
        "  let ParserMatchClass = YSXAutoVMaskAsmOperand;",
        '  let PrintMethod = "printVMaskReg";',
        '  let EncoderMethod = "getVMaskReg";',
        '  let DecoderMethod = "decodeVMaskReg";',
        '  let OperandNamespace = "YSXOp";',
        '  let OperandType = "OPERAND_VMASK";',
        "}",
        "",
        "def YSXAutoVMaskCarryInAsmOperand : AsmOperandClass {",
        '  let Name = "YSXAutoVMaskCarryInRegOpOperand";',
        '  let RenderMethod = "addRegOperands";',
        '  let PredicateMethod = "isV0Reg";',
        '  let DiagnosticType = "InvalidYSXAutoVMaskCarryInRegister";',
        '  let DiagnosticString = "operand must be v0";',
        "}",
        "",
        "def YSXAutoVMaskCarryInOp : RegisterOperand<VMV0> {",
        "  let ParserMatchClass = YSXAutoVMaskCarryInAsmOperand;",
        '  let EncoderMethod = "getVMaskReg";',
        '  let DecoderMethod = "decodeVMaskCarryInReg";',
        "}",
        "",
    ]

    for instruction in sorted(instructions, key=lambda record: record.mnemonic):
        lines.extend(_emit_instruction(instruction))
        lines.append("")

    aliases = [
        (alias, instruction.mnemonic)
        for instruction in instructions
        for alias in instruction.aliases
    ]
    for alias, canonical in sorted(aliases):
        lines.append(f'def : MnemonicAlias<"{alias}", "{canonical}">;')

    return "\n".join(lines).rstrip() + "\n"


def _emit_tiny_v_pseudos(instructions) -> str:
    lines = [GENERATED_HEADER.rstrip()]
    for instruction in sorted(instructions, key=lambda record: record.mnemonic):
        if not instruction.pseudos:
            continue
        matrix = instruction.pseudos.get("matrix")
        if isinstance(matrix, dict):
            lines.append(
                f"// auto-td-pseudo: {instruction.mnemonic} matrix "
                f"element_types={_manifest_list(matrix.get('element_types', []))} "
                f"lmuls={matrix.get('lmuls', '')} "
                f"masked={_manifest_bool(matrix.get('masked', False))} "
                f"policy={matrix.get('policy', '')}"
            )
        else:
            lines.append(
                f"// auto-td-pseudo: {instruction.mnemonic} "
                f"{_manifest_mapping(instruction.pseudos)}"
            )
    if len(lines) == 1:
        return _empty_file("tiny-v pseudos")
    return "\n".join(lines).rstrip() + "\n"


def _emit_tiny_v_patterns(instructions) -> str:
    lines = [GENERATED_HEADER.rstrip()]
    for instruction in sorted(instructions, key=lambda record: record.mnemonic):
        for pattern in instruction.patterns:
            kind = pattern.get("kind", "")
            if kind == "intrinsic_to_pseudo":
                lines.append(
                    f"// auto-td-pattern: {instruction.mnemonic} "
                    f"intrinsic={pattern.get('intrinsic', '')} "
                    f"operation={pattern.get('operation', '')} "
                    f"record={_record_name(instruction)}"
                )
            else:
                lines.append(
                    f"// auto-td-pattern: {instruction.mnemonic} "
                    f"kind={kind} {_manifest_mapping(pattern, skip=('kind',))} "
                    f"record={_record_name(instruction)}"
                )
    if len(lines) == 1:
        return _empty_file("tiny-v patterns")
    return "\n".join(lines).rstrip() + "\n"


def _emit_tiny_v_builtins(instructions) -> str:
    lines = [GENERATED_HEADER.rstrip()]
    for instruction in sorted(instructions, key=lambda record: record.mnemonic):
        if not instruction.builtin:
            continue
        header = instruction.builtin["header"]
        overloaded = _manifest_bool(instruction.builtin.get("overloaded", False))
        for name in instruction.builtin["names"]:
            lines.append(
                f"// auto-td-builtin: {instruction.mnemonic} "
                f"header={header} name={name} overloaded={overloaded} "
                f"record={_record_name(instruction)}"
            )
    if len(lines) == 1:
        return _empty_file("tiny-v builtins")
    return "\n".join(lines).rstrip() + "\n"


def _emit_instrinfo(instructions) -> str:
    lines = [GENERATED_HEADER.rstrip()]
    for instruction in sorted(instructions, key=lambda record: record.mnemonic):
        lines.append("")
        lines.extend(_emit_instruction(instruction))
    return "\n".join(lines).rstrip() + "\n"


def _emit_instruction(instruction) -> list[str]:
    record_name = _record_name(instruction)
    outs, ins, asm_operands = _operand_dags(instruction)
    assignments = _assignments(instruction)
    declarations = _field_declarations(assignments)
    inst_format = _inst_format(instruction)

    lines = [
        f"// opcode-source: {_opcode_source_name(instruction)}",
        f"def {record_name} : RVInst<{outs}, {ins}, "
        f'"{instruction.mnemonic}", "{asm_operands}", [], {inst_format}> {{',
        f"  let Predicates = [{_predicate(instruction)}];",
        "  let hasSideEffects = "
        f"{1 if instruction.effects.has_side_effects else 0};",
        f"  let mayLoad = {1 if instruction.effects.may_load else 0};",
        f"  let mayStore = {1 if instruction.effects.may_store else 0};",
        "  let hasNoSchedulingInfo = 1;",
    ]
    if instruction.effects.implicit_uses:
        lines.append(f"  let Uses = [{_implicit_reg_list(instruction.effects.implicit_uses)}];")
    if instruction.effects.implicit_defs:
        lines.append(f"  let Defs = [{_implicit_reg_list(instruction.effects.implicit_defs)}];")
    for declaration in declarations:
        lines.append(f"  {declaration}")
    for assignment in assignments:
        inst_range = _inst_range(assignment.msb, assignment.lsb)
        lines.append(f"  let {inst_range} = {assignment.expr};")
    lines.append("}")
    return lines


def _record_name(instruction) -> str:
    return "YSX_AUTO_" + source_key_from_mnemonic(instruction.mnemonic).upper()


def _manifest_mapping(mapping: dict, skip: tuple[str, ...] = ()) -> str:
    items = []
    for key in sorted(mapping):
        if key in skip:
            continue
        value = mapping[key]
        if isinstance(value, list) or isinstance(value, tuple):
            value = _manifest_list(value)
        elif isinstance(value, bool):
            value = _manifest_bool(value)
        items.append(f"{key}={value}")
    return " ".join(items)


def _manifest_list(value) -> str:
    if isinstance(value, list) or isinstance(value, tuple):
        return ",".join(str(item) for item in value)
    return str(value)


def _manifest_bool(value) -> str:
    return "true" if bool(value) else "false"


def _predicate(instruction) -> str:
    if instruction.path.parent.name == "tiny-f":
        return "HasStdExtXTinyF"
    return "HasStdExtXTinyV"


def _inst_format(instruction) -> str:
    fields = set(instruction.opcode.fields)
    if {"imm12hi", "imm12lo"}.issubset(fields):
        return "InstFormatS"
    if "imm12" in fields:
        return "InstFormatI"
    if instruction.mnemonic in {"vsetvli", "vsetivli"}:
        return "InstFormatI"
    return "InstFormatR"


def _implicit_reg_list(registers: tuple[str, ...]) -> str:
    return ", ".join(registers)


def _operand_dags(instruction) -> tuple[str, str, str]:
    if not instruction.operands_out and not instruction.operands_in:
        raise ValueError(f"{instruction.path}: missing taxonomy operands")
    outs = [_td_operand(operand) for operand in instruction.operands_out]
    ins = [_td_operand(operand) for operand in instruction.operands_in]

    return _dag("outs", outs), _dag("ins", ins), _asm_operands(instruction)


def _asm_operands(instruction) -> str:
    mask = any(operand.operand == "VMaskOp" for operand in instruction.operands_in)
    base = next(
        (operand for operand in instruction.operands_in if operand.role == "base"),
        None,
    )
    offset = next(
        (operand for operand in instruction.operands_in if operand.role == "offset"),
        None,
    )
    folded_offset_mem = base and offset
    operands = [
        _asm_operand(operand)
        for operand in (*instruction.operands_out, *instruction.operands_in)
        if operand.operand != "VMaskOp"
        and not (folded_offset_mem and operand is base)
        and not (folded_offset_mem and operand is offset)
    ]
    if folded_offset_mem:
        operands.append("${" + offset.field + "}(${" + base.field + "})")
    asm = ", ".join(operands)
    if mask:
        asm += "$vm"
    return asm


def _td_operand(operand) -> str:
    if not operand.field:
        raise ValueError(f"operand {operand.role} is missing an encoding field")
    if operand.operand == "VMaskOp":
        return f"YSXAutoVMaskOp:${operand.field}"
    if operand.operand == "VMaskCarryInOp":
        return f"YSXAutoVMaskCarryInOp:${operand.field}"
    if operand.operand == "UImm3":
        return f"uimm3:${operand.field}"
    if operand.operand == "UImm5":
        return f"uimm5:${operand.field}"
    if operand.operand == "UImm10":
        return f"uimm10:${operand.field}"
    if operand.operand == "UImm11":
        return f"uimm11:${operand.field}"
    if operand.operand == "SImm12":
        return f"simm12_lo:${operand.field}"
    if operand.operand == "GPRMem":
        return f"GPRMem:${operand.field}"
    if operand.reg_class == "VR":
        return f"VR:${operand.field}"
    if operand.reg_class == "FPR32":
        return f"FPR32:${operand.field}"
    if operand.reg_class == "GPR" and operand.role == "base":
        return f"GPRMemZeroOffset:${operand.field}"
    if operand.reg_class == "GPR":
        return f"GPR:${operand.field}"
    if operand.reg_class:
        return f"{operand.reg_class}:${operand.field}"
    raise ValueError(f"operand {operand.role} is missing reg_class or operand")


def _asm_operand(operand) -> str:
    if not operand.field:
        raise ValueError(f"operand {operand.role} is missing an encoding field")
    return f"${operand.field}"


def _dag(name: str, operands: list[str]) -> str:
    if not operands:
        return f"({name})"
    return f"({name} " + ", ".join(operands) + ")"


def _assignments(instruction) -> list[Assignment]:
    assignments: list[Assignment] = []
    ranges = {
        field_range.name: (field_range.msb, field_range.lsb)
        for field_range in instruction.opcode.field_ranges
    }
    carry_in_mask = _carry_in_mask_field(instruction)
    for field in instruction.opcode.fields:
        if field == "nf":
            msb, lsb = _field_range(instruction, ranges, field)
            assignments.append(Assignment(msb, lsb, _binary(0, msb - lsb + 1)))
            continue
        if field == "imm12hi":
            msb, lsb = _field_range(instruction, ranges, field)
            assignments.append(Assignment(msb, lsb, "imm12{11-5}"))
            continue
        if field == "imm12lo":
            msb, lsb = _field_range(instruction, ranges, field)
            assignments.append(Assignment(msb, lsb, "imm12{4-0}"))
            continue
        msb, lsb = _field_range(instruction, ranges, field)
        assignments.append(Assignment(msb, lsb, field))

    for fixed in instruction.opcode.fixed_bits:
        msb, lsb, value = _parse_fixed_bits(instruction, fixed)
        if carry_in_mask and msb == lsb == 25 and value == 0:
            assignments.append(Assignment(msb, lsb, carry_in_mask))
            continue
        assignments.append(Assignment(msb, lsb, _binary(value, msb - lsb + 1)))

    return sorted(assignments, key=lambda item: (-item.msb, -item.lsb))


def _carry_in_mask_field(instruction) -> str | None:
    return next(
        (
            operand.field
            for operand in instruction.operands_in
            if operand.operand == "VMaskCarryInOp" and operand.field
        ),
        None,
    )


def _field_range(instruction, ranges: dict[str, tuple[int, int]], field: str):
    if field not in ranges:
        raise ValueError(
            f"{instruction.path}: missing arg_lut range for opcode field {field}"
        )
    return ranges[field]


def _field_declarations(assignments: list[Assignment]) -> list[str]:
    widths: dict[str, int] = {}
    for assignment in assignments:
        name, width = _declaration_for_expr(assignment)
        if name is None:
            continue
        widths[name] = max(widths.get(name, 0), width)

    declarations: list[str] = []
    for name, width in widths.items():
        if width == 1:
            declarations.append(f"bit {name};")
        else:
            declarations.append(f"bits<{width}> {name};")
    return declarations


def _declaration_for_expr(assignment: Assignment) -> tuple[str | None, int]:
    if assignment.expr.isidentifier():
        return assignment.expr, assignment.msb - assignment.lsb + 1
    match = re.fullmatch(r"([A-Za-z_][A-Za-z0-9_]*)\{(\d+)-(\d+)\}", assignment.expr)
    if not match:
        return None, 0
    root, msb_text, lsb_text = match.groups()
    msb = int(msb_text)
    lsb = int(lsb_text)
    if msb < lsb:
        raise ValueError(f"invalid field slice expression {assignment.expr}")
    return root, msb + 1


def _parse_fixed_bits(instruction, token: str) -> tuple[int, int, int]:
    lhs, rhs = token.split("=", 1)
    if ".." in lhs:
        msb_text, lsb_text = lhs.split("..", 1)
        msb = int(msb_text)
        lsb = int(lsb_text)
    else:
        msb = lsb = int(lhs)
    if msb < lsb:
        raise ValueError(f"{instruction.path}: invalid fixed bit range {token}")
    value = int(rhs, 0)
    width = msb - lsb + 1
    if value >= (1 << width):
        raise ValueError(f"{instruction.path}: fixed bit value too wide: {token}")
    return msb, lsb, value


def _binary(value: int, width: int) -> str:
    return "0b" + format(value, f"0{width}b")


def _inst_range(msb: int, lsb: int) -> str:
    if msb == lsb:
        return f"Inst{{{msb}}}"
    return f"Inst{{{msb}-{lsb}}}"


def _opcode_source_name(instruction) -> str:
    source = instruction.opcode_source
    return f"{source.repo}/{source.extension}/{source.key}"
