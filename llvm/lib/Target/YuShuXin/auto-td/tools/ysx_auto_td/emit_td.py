from dataclasses import dataclass
from pathlib import Path

from .opcodes import source_key_from_mnemonic


GENERATED_HEADER = "// generated by ysx_auto_td_gen\n"
OUTPUTS = (
    "YSXGenAutoTinyFInstrInfo.inc",
    "YSXGenAutoTinyVInstrInfo.inc",
    "YSXGenAutoTinyVPseudos.inc",
    "YSXGenAutoTinyVPatterns.inc",
    "YSXGenAutoTinyVBuiltins.inc",
)


@dataclass(frozen=True)
class Assignment:
    msb: int
    lsb: int
    expr: str


def write_td_outputs(out_dir: Path, instructions) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    tiny_v = [
        instruction
        for instruction in instructions
        if instruction.path.parent.name == "tiny-v"
    ]

    content = {
        "YSXGenAutoTinyFInstrInfo.inc": _empty_file("tiny-f instrinfo"),
        "YSXGenAutoTinyVInstrInfo.inc": _emit_tiny_v_instrinfo(tiny_v),
        "YSXGenAutoTinyVPseudos.inc": _empty_file("tiny-v pseudos"),
        "YSXGenAutoTinyVPatterns.inc": _empty_file("tiny-v patterns"),
        "YSXGenAutoTinyVBuiltins.inc": _empty_file("tiny-v builtins"),
    }

    for output in OUTPUTS:
        (out_dir / output).write_text(content[output])


def _empty_file(name: str) -> str:
    return f"{GENERATED_HEADER}// {name}: no generated records yet\n"


def _emit_tiny_v_instrinfo(instructions) -> str:
    lines = [
        GENERATED_HEADER.rstrip(),
        "",
        "// YSX tiny-v operand support generated from structured YAML.",
        "def YSXAutoVMaskAsmOperand : AsmOperandClass {",
        '  let Name = "YSXAutoVMaskRegOpOperand";',
        '  let RenderMethod = "addRegOperands";',
        '  let PredicateMethod = "isV0Reg";',
        '  let ParserMethod = "parseVMaskReg";',
        "  let IsOptional = 1;",
        '  let DefaultMethod = "defaultMaskRegOp";',
        '  let DiagnosticType = "InvalidYSXAutoVMaskRegister";',
        '  let DiagnosticString = "operand must be v0.t";',
        "}",
        "",
        "def YSXAutoVMaskOp : RegisterOperand<VMV0> {",
        "  let ParserMatchClass = YSXAutoVMaskAsmOperand;",
        '  let PrintMethod = "printVMaskReg";',
        '  let EncoderMethod = "getVMaskReg";',
        '  let DecoderMethod = "decodeVMaskReg";',
        '  let OperandNamespace = "YSXOp";',
        '  let OperandType = "OPERAND_VMASK";',
        "}",
        "",
    ]

    for instruction in sorted(instructions, key=lambda record: record.mnemonic):
        lines.extend(_emit_instruction(instruction))
        lines.append("")

    aliases = [
        (alias, instruction.mnemonic)
        for instruction in instructions
        for alias in instruction.aliases
    ]
    for alias, canonical in sorted(aliases):
        lines.append(f'def : MnemonicAlias<"{alias}", "{canonical}">;')

    return "\n".join(lines).rstrip() + "\n"


def _emit_instruction(instruction) -> list[str]:
    record_name = "YSX_AUTO_" + source_key_from_mnemonic(instruction.mnemonic).upper()
    outs, ins, asm_operands = _operand_dags(instruction)
    assignments = _assignments(instruction)
    declarations = _field_declarations(assignments)

    lines = [
        f"// opcode-source: {_opcode_source_name(instruction)}",
        f"def {record_name} : RVInst<{outs}, {ins}, "
        f'"{instruction.mnemonic}", "{asm_operands}", [], InstFormatR> {{',
        "  let Predicates = [HasStdExtXTinyV];",
        "  let hasSideEffects = "
        f"{1 if instruction.effects.has_side_effects else 0};",
        f"  let mayLoad = {1 if instruction.effects.may_load else 0};",
        f"  let mayStore = {1 if instruction.effects.may_store else 0};",
        "  let hasNoSchedulingInfo = 1;",
        "  let Uses = [VL, VTYPE];",
    ]
    for declaration in declarations:
        lines.append(f"  {declaration}")
    for assignment in assignments:
        inst_range = _inst_range(assignment.msb, assignment.lsb)
        lines.append(f"  let {inst_range} = {assignment.expr};")
    lines.append("}")
    return lines


def _operand_dags(instruction) -> tuple[str, str, str]:
    if not instruction.operands_out and not instruction.operands_in:
        raise ValueError(f"{instruction.path}: missing taxonomy operands")
    outs = [_td_operand(operand) for operand in instruction.operands_out]
    ins = [_td_operand(operand) for operand in instruction.operands_in]

    return _dag("outs", outs), _dag("ins", ins), _asm_operands(instruction)


def _asm_operands(instruction) -> str:
    mask = any(operand.operand == "VMaskOp" for operand in instruction.operands_in)
    operands = [
        _asm_operand(operand)
        for operand in (*instruction.operands_out, *instruction.operands_in)
        if operand.operand != "VMaskOp"
    ]
    asm = ", ".join(operands)
    if mask:
        asm += "$vm"
    return asm


def _td_operand(operand) -> str:
    if not operand.field:
        raise ValueError(f"operand {operand.role} is missing an encoding field")
    if operand.operand == "VMaskOp":
        return f"YSXAutoVMaskOp:${operand.field}"
    if operand.reg_class == "VR":
        return f"VR:${operand.field}"
    if operand.reg_class == "GPR" and operand.role == "base":
        return f"GPRMemZeroOffset:${operand.field}"
    if operand.reg_class == "GPR":
        return f"GPR:${operand.field}"
    if operand.reg_class:
        return f"{operand.reg_class}:${operand.field}"
    raise ValueError(f"operand {operand.role} is missing reg_class or operand")


def _asm_operand(operand) -> str:
    if not operand.field:
        raise ValueError(f"operand {operand.role} is missing an encoding field")
    if operand.reg_class == "GPR" and operand.role == "base":
        return "${" + operand.field + "}"
    return f"${operand.field}"


def _dag(name: str, operands: list[str]) -> str:
    if not operands:
        return f"({name})"
    return f"({name} " + ", ".join(operands) + ")"


def _assignments(instruction) -> list[Assignment]:
    assignments: list[Assignment] = []
    ranges = {
        field_range.name: (field_range.msb, field_range.lsb)
        for field_range in instruction.opcode.field_ranges
    }
    for field in instruction.opcode.fields:
        if field == "nf":
            msb, lsb = _field_range(instruction, ranges, field)
            assignments.append(Assignment(msb, lsb, _binary(0, msb - lsb + 1)))
            continue
        msb, lsb = _field_range(instruction, ranges, field)
        assignments.append(Assignment(msb, lsb, field))

    for fixed in instruction.opcode.fixed_bits:
        msb, lsb, value = _parse_fixed_bits(instruction, fixed)
        assignments.append(Assignment(msb, lsb, _binary(value, msb - lsb + 1)))

    return sorted(assignments, key=lambda item: (-item.msb, -item.lsb))


def _field_range(instruction, ranges: dict[str, tuple[int, int]], field: str):
    if field not in ranges:
        raise ValueError(
            f"{instruction.path}: missing arg_lut range for opcode field {field}"
        )
    return ranges[field]


def _field_declarations(assignments: list[Assignment]) -> list[str]:
    declarations: list[str] = []
    seen: set[str] = set()
    for assignment in assignments:
        if not assignment.expr.isidentifier() or assignment.expr in seen:
            continue
        seen.add(assignment.expr)
        width = assignment.msb - assignment.lsb + 1
        if width == 1:
            declarations.append(f"bit {assignment.expr};")
        else:
            declarations.append(f"bits<{width}> {assignment.expr};")
    return declarations


def _parse_fixed_bits(instruction, token: str) -> tuple[int, int, int]:
    lhs, rhs = token.split("=", 1)
    if ".." in lhs:
        msb_text, lsb_text = lhs.split("..", 1)
        msb = int(msb_text)
        lsb = int(lsb_text)
    else:
        msb = lsb = int(lhs)
    if msb < lsb:
        raise ValueError(f"{instruction.path}: invalid fixed bit range {token}")
    value = int(rhs, 0)
    width = msb - lsb + 1
    if value >= (1 << width):
        raise ValueError(f"{instruction.path}: fixed bit value too wide: {token}")
    return msb, lsb, value


def _binary(value: int, width: int) -> str:
    return "0b" + format(value, f"0{width}b")


def _inst_range(msb: int, lsb: int) -> str:
    if msb == lsb:
        return f"Inst{{{msb}}}"
    return f"Inst{{{msb}-{lsb}}}"


def _opcode_source_name(instruction) -> str:
    source = instruction.opcode_source
    return f"{source.repo}/{source.extension}/{source.key}"
